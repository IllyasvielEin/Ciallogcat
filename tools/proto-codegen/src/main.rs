//! Regenerate bindings with the pinned, vendored protoc toolchain.
use std::error::Error;
use std::fs;
use std::path::PathBuf;
use std::process::Command;
use std::time::{SystemTime, UNIX_EPOCH};

const PREFIX: &str = "// AOSP Android 16 r1 schema, Apache-2.0; see proto/README.md.\n// Generated by tools/proto-codegen; do not edit by hand.\n";

fn main() -> Result<(), Box<dyn Error>> {
    let check = match std::env::args().skip(1).collect::<Vec<_>>().as_slice() {
        [] => false,
        [arg] if arg == "--check" => true,
        _ => return Err("usage: ciallogcat-proto-codegen [--check]".into()),
    };
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let protoc = protoc_bin_vendored::protoc_bin_path()?;
    let version = Command::new(&protoc).arg("--version").output()?;
    if !version.status.success() {
        return Err("vendored protoc --version failed".into());
    }
    let version = String::from_utf8(version.stdout)?;
    if version.trim() != "libprotoc 31.1" {
        return Err(format!("unexpected vendored protoc version: {}", version.trim()).into());
    }
    eprintln!("prost-build 0.14.4; {}", version.trim());
    let directory = std::env::temp_dir().join(format!(
        "ciallogcat-proto-codegen-{}-{}",
        std::process::id(),
        SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos()
    ));
    fs::create_dir(&directory)?;
    struct Cleanup(PathBuf);
    impl Drop for Cleanup {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }
    let _cleanup = Cleanup(directory.clone());
    prost_build::Config::new()
        .protoc_executable(protoc)
        .out_dir(&directory)
        .compile_protos(&[root.join("proto/logcat.proto")], &[root.join("proto")])?;
    let generated = fs::read_to_string(directory.join("com.android.logcat.proto.rs"))?;
    let expected = format!("{PREFIX}{generated}");
    let destination = root.join("src/protobuf/generated.rs");
    if check {
        if fs::read_to_string(&destination)? != expected {
            return Err("protobuf bindings differ; run tools/proto-codegen without --check".into());
        }
        println!("protobuf bindings match the pinned schema and generator");
    } else {
        fs::write(destination, expected)?;
        println!("updated src/protobuf/generated.rs");
    }
    Ok(())
}
